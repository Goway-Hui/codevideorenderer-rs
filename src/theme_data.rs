pub struct Theme {
    /// Pygments 风格名称（`--style` 也接受此名称）。
    pub name: &'static str,
    /// 编辑器背景色。
    pub background: (u8, u8, u8),
    /// 默认文本颜色。
    pub foreground: (u8, u8, u8),
    /// 稀疏的 token 颜色表；缺失的 token 回退到其父类别。
    pub styles: &'static [ThemeStyle],
}

